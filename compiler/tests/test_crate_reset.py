"""reset() clears a crate furiosa-compile generated and refuses any other folder.

    PYTHONPATH=compiler compiler/.venv/bin/python compiler/tests/test_crate_reset.py
"""

import tempfile
from pathlib import Path

from furiosa_compiler.crate import CrateError, reset


def main():
    with tempfile.TemporaryDirectory() as tmp:
        foreign = Path(tmp) / "foreign"
        (foreign / "src").mkdir(parents=True)
        (foreign / "src" / "main.rs").write_text("fn main() {}\n")
        (foreign / "Cargo.toml").write_text('[package]\nname = "mine"\n')
        try:
            reset(foreign)
            raise AssertionError("reset cleared a crate it did not generate")
        except CrateError:
            pass
        assert (foreign / "src" / "main.rs").exists()

        generated = Path(tmp) / "generated"
        (generated / "src").mkdir(parents=True)
        (generated / "Cargo.toml").write_text('description = "Generated by furiosa-compile from m.py; do not edit."\n')
        reset(generated)
        assert not (generated / "src").exists() and not (generated / "Cargo.toml").exists()

        reset(Path(tmp) / "new")  # a folder that does not exist yet is fine
    print("ok")


if __name__ == "__main__":
    main()
