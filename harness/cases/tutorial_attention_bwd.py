def forward(z=1, h=2, n_ctx=256, head_dim=64, sm_scale=0.5, dtype="fp16"):
    g = Graph(f"attention_bwd(z={z}, h={h}, n_ctx={n_ctx}, head_dim={head_dim}, causal, dtype={dtype})")
    shape = (z, h, n_ctx, head_dim)
    q, k, v = (g.buffer(n, dtype, shape, "input") for n in ("q", "k", "v"))
    k_scaled = g.buffer("k_scaled", dtype, shape, "activation")  # the host's k * (sm_scale / ln 2)
    do = g.buffer("do", dtype, shape, "input")
    o = g.buffer("o", dtype, shape, "activation")
    m = g.buffer("M", "fp32", (z, h, n_ctx), "activation")
    delta = g.buffer("delta", "fp32", (z, h, n_ctx), "activation")
    dq, dk, dv = (g.buffer(n, dtype, shape, "output") for n in ("dq", "dk", "dv"))
    g.launch(_attn_fwd, (triton.cdiv(n_ctx, 64), z * h), sm_scale=sm_scale, M=m, Z=z, H=h, desc_q=q, desc_k=k,
             desc_v=v, desc_o=o, N_CTX=n_ctx, HEAD_DIM=head_dim, BLOCK_M=64, BLOCK_N=64, FP8_OUTPUT=False, STAGE=3,
             warp_specialize=False, IS_HOPPER=False)
    numel = z * h * n_ctx * head_dim
    g.launch(_scale, (triton.cdiv(numel, 1024),), x_ptr=k, y_ptr=k_scaled, n=numel, c=sm_scale * 1.4426950408889634,
             BLOCK=1024)
    g.launch(_attn_bwd_preprocess, (n_ctx // 128, z * h), O=o, DO=do, Delta=delta, Z=z, H=h, N_CTX=n_ctx,
             BLOCK_M=128, HEAD_DIM=head_dim)
    stride = (h * n_ctx * head_dim, n_ctx * head_dim, head_dim, 1)
    g.launch(_attn_bwd, (n_ctx // 128, 1, z * h), Q=q, K=k_scaled, V=v, sm_scale=sm_scale, DO=do, DQ=dq, DK=dk, DV=dv,
             M=m, D=delta, stride_z=stride[0], stride_h=stride[1], stride_tok=stride[2], stride_d=stride[3], H=h,
             N_CTX=n_ctx, BLOCK_M1=32, BLOCK_N1=128, BLOCK_M2=128, BLOCK_N2=32, BLK_SLICE_FACTOR=2,
             HEAD_DIM=head_dim, CAUSAL=True)
    return g


def graphs():
    return [forward()]
