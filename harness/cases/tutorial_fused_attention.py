def forward(z=1, h=2, n_ctx=256, head_dim=64, sm_scale=0.5, dtype="fp16"):
    g = Graph(f"attention(z={z}, h={h}, n_ctx={n_ctx}, head_dim={head_dim}, causal, dtype={dtype})")
    q = g.buffer("q", dtype, (z, h, n_ctx, head_dim), "input")
    k = g.buffer("k", dtype, (z, h, n_ctx, head_dim), "input")
    v = g.buffer("v", dtype, (z, h, n_ctx, head_dim), "input")
    o = g.buffer("o", dtype, (z, h, n_ctx, head_dim), "output")
    m = g.buffer("M", "fp32", (z, h, n_ctx), "output")
    block_m, block_n = 64, 64
    g.launch(_attn_fwd, (triton.cdiv(n_ctx, block_m), z * h), sm_scale=sm_scale, M=m, Z=z, H=h, desc_q=q, desc_k=k,
             desc_v=v, desc_o=o, N_CTX=n_ctx, HEAD_DIM=head_dim, BLOCK_M=block_m, BLOCK_N=block_n,
             FP8_OUTPUT=False, STAGE=3, warp_specialize=False, IS_HOPPER=False)
    return g


def graphs():
    return [forward()]
