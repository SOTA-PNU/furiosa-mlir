# Kernels
# ---------------------------------------------------------------------------------------------------


# python/tutorials/04-low-memory-dropout.py:110-131
@triton.jit
def _seeded_dropout(
    x_ptr,
    output_ptr,
    n_elements,
    p,
    seed,
    BLOCK_SIZE: tl.constexpr,
):
    # compute memory offsets of elements handled by this instance
    pid = tl.program_id(axis=0)
    block_start = pid * BLOCK_SIZE
    offsets = block_start + tl.arange(0, BLOCK_SIZE)
    # load data from x
    mask = offsets < n_elements
    x = tl.load(x_ptr + offsets, mask=mask)
    # randomly prune it
    random = tl.rand(seed, offsets)
    x_keep = random > p
    # write-back
    output = tl.where(x_keep, x / (1 - p), 0.0)
    tl.store(output_ptr + offsets, output, mask=mask)


# ---------------------------------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------------------------------


def forward(n=98432, p=0.5, seed=123, dtype="fp32"):
    g = Graph(f"seeded_dropout(n={n}, p={p}, seed={seed}, dtype={dtype})")
    x = g.buffer("x", dtype, (n,), "input")
    out = g.buffer("output", dtype, (n,), "output")
    g.launch(_seeded_dropout, (triton.cdiv(n, 1024),), x_ptr=x, output_ptr=out, n_elements=n, p=p, seed=seed,
             BLOCK_SIZE=1024)
    return g


def graphs():
    return [forward()]
